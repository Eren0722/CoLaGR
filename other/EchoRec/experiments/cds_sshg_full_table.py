import argparse
import gc
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Sequence

import numpy as np
import torch

CURRENT_DIR = Path(__file__).resolve().parent
if str(CURRENT_DIR) not in sys.path:
    sys.path.insert(0, str(CURRENT_DIR))

import cds_sshg_diagnosis as base_diag


PROJECT_ROOT = base_diag.PROJECT_ROOT


@dataclass
class VariantSpec:
    label: str
    save_dir: str
    teacher_ckpt: str


VARIANT_ORDER = {
    "Pure-SI": 0,
    "w/o Item-CL": 1,
    "w/o User-CL": 2,
    "EchoRec": 3,
    "w/o Match": 4,
}


